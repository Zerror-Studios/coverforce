/**
 * Deterministic pseudo-random generator (mulberry32).
 *
 * Use inside render / useMemo instead of Math.random so the result is pure:
 * the same seed always produces the same sequence of numbers in [0, 1).
 */
export function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Combine numbers into a 32-bit seed for seededRandom. */
export function hashSeed(...values: number[]): number {
  let h = 2166136261;
  for (const v of values) {
    h ^= Math.round(v * 1000);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
